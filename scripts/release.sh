#!/bin/sh
# Cuts an emailulator release:
#   version bump -> commit -> package (sign, notarize) -> push -> tag -> publish.
#
# The release is assembled from two places. The macOS archive is built and
# signed here, because the Developer ID certificate lives in this machine's
# keychain. The Linux archives are built by the release workflow when the tag
# is pushed, which leaves them on a DRAFT release. This script then adds the
# macOS archive and a checksums.txt covering all three, and publishes.
#
# The draft is the point: install.sh resolves "latest", and a draft is never
# latest, so nobody can install a release that is still missing an archive or
# its checksums. Anything failing after the tag is pushed leaves a draft
# behind, not a broken release.
#
# Usage:
#   scripts/release.sh (patch | minor | major | X.Y.Z | current) [--notes <file>] [--yes] [--dry-run]
set -eu
cd "$(dirname "$0")/.."

REMOTE=origin
BRANCH=main
LEVEL=
NOTES=
ASSUME_YES=0
DRY_RUN=0

die() { printf '%s\n' "error: $*" >&2; exit 1; }

usage() {
  cat <<'USAGE'
usage: scripts/release.sh (patch | minor | major | X.Y.Z | current) [--notes <file>] [--yes] [--dry-run]

  patch|minor|major|X.Y.Z
                  how to bump the version in Cargo.toml
  current         release the version Cargo.toml already has, with no bump
  --notes <file>  release notes; without it GitHub's generated notes are kept
  --yes, -y       skip the confirmation prompt
  --dry-run       print the plan and exit without changing anything
USAGE
}

while [ $# -gt 0 ]; do
  case "$1" in
    --notes) [ $# -ge 2 ] || die "--notes needs a file"; NOTES=$2; shift 2 ;;
    --notes=*) NOTES=${1#--notes=}; shift ;;
    --yes|-y) ASSUME_YES=1; shift ;;
    --dry-run) DRY_RUN=1; shift ;;
    patch|minor|major|current) LEVEL=$1; shift ;;
    [0-9]*.[0-9]*.[0-9]*) LEVEL=$1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; die "unknown argument: $1" ;;
  esac
done

[ -n "$LEVEL" ] || { usage >&2; die "say how to version this release"; }
if [ -n "$NOTES" ]; then
  [ -s "$NOTES" ] || die "notes file is missing or empty: $NOTES"
fi

# --- Preconditions -----------------------------------------------------------
command -v gh >/dev/null 2>&1 || die "gh (GitHub CLI) is required"
gh auth status >/dev/null 2>&1 || die "gh is not authenticated — run: gh auth login"
# gh has one active account for the whole machine. A wrong one fails here, as
# "not found", rather than halfway through publishing.
gh repo view --json name >/dev/null 2>&1 \
  || die "gh cannot see this repository — is the right account active? (gh auth switch)"

[ -z "$(git status --porcelain)" ] || die "working tree is dirty — commit or stash first"
current_branch=$(git rev-parse --abbrev-ref HEAD)
[ "$current_branch" = "$BRANCH" ] || die "on branch '$current_branch', expected '$BRANCH'"

# Signing is checked before the bump: finding out at the packaging step would
# leave a release commit with nothing to release.
./scripts/package.sh --preflight >/dev/null || die "signing is not ready — see scripts/package.sh --preflight"

git fetch --quiet "$REMOTE" "$BRANCH"
if [ -n "$(git rev-list "HEAD..$REMOTE/$BRANCH")" ]; then
  die "behind $REMOTE/$BRANCH — pull first"
fi

CURRENT=$(sed -n 's/^version = "\(.*\)"$/\1/p' Cargo.toml | head -1)
[ -n "$CURRENT" ] || die "could not read the version from Cargo.toml"

case "$LEVEL" in
  current) VERSION=$CURRENT ;;
  patch|minor|major)
    MAJOR=$(printf '%s' "$CURRENT" | cut -d. -f1)
    MINOR=$(printf '%s' "$CURRENT" | cut -d. -f2)
    PATCH=$(printf '%s' "$CURRENT" | cut -d. -f3)
    case "$LEVEL" in
      patch) PATCH=$((PATCH + 1)) ;;
      minor) MINOR=$((MINOR + 1)); PATCH=0 ;;
      major) MAJOR=$((MAJOR + 1)); MINOR=0; PATCH=0 ;;
    esac
    VERSION="$MAJOR.$MINOR.$PATCH"
    ;;
  *) VERSION=$LEVEL ;;
esac
TAG="v$VERSION"

# A tag that already exists means an earlier run got here first; resolving that
# is a judgement call, not something to paper over.
[ "$(git tag -l "$TAG" | wc -l)" -eq 0 ] || die "tag $TAG already exists locally"
[ "$(git ls-remote --tags "$REMOTE" "refs/tags/$TAG" | wc -l)" -eq 0 ] \
  || die "tag $TAG already exists on $REMOTE"

MAC_ARCHIVE="dist/emailulator_${VERSION}_darwin_arm64.tar.gz"

cat <<PLAN
Release plan
  version      $CURRENT -> $VERSION   (Cargo.toml)
  tag          $TAG
  macOS        $MAC_ARCHIVE   (built, signed and notarized here)
  Linux        amd64 and arm64 archives, built by the release workflow
  notes        ${NOTES:-generated by GitHub}
  remote       $REMOTE/$BRANCH
PLAN

if [ "$DRY_RUN" -eq 1 ]; then
  echo "[dry run] nothing was changed."
  exit 0
fi

if [ "$ASSUME_YES" -ne 1 ]; then
  printf 'Proceed? [y/N] '
  read -r reply
  case "$reply" in y|Y|yes|YES) ;; *) echo "aborted."; exit 1 ;; esac
fi

# --- Gate on the tests -------------------------------------------------------
echo "==> cargo test"
cargo test --locked --features desktop >/dev/null 2>&1 || die "tests failed — not releasing"

# --- Bump + commit (local only, for now) -------------------------------------
if [ "$VERSION" != "$CURRENT" ]; then
  echo "==> bumping the version to $VERSION"
  sed -i '' "s/^version = \"$CURRENT\"\$/version = \"$VERSION\"/" Cargo.toml
  # Cargo.lock records this crate's own version too.
  cargo update --workspace --offline >/dev/null 2>&1 || die "could not update Cargo.lock"
  git diff --quiet -- Cargo.toml && die "the version bump changed nothing — check Cargo.toml"
  git add Cargo.toml Cargo.lock
  git commit -m "release $VERSION"
fi
RELEASE_COMMIT=$(git rev-parse HEAD)

# --- Package -----------------------------------------------------------------
# After the bump, so the binary carries the new version and this commit's hash;
# before the push, so a failed signature or notarization leaves nothing public
# to undo (`git reset --hard HEAD~1` drops the bump).
echo "==> packaging the macOS build"
./scripts/package.sh
[ -f "$MAC_ARCHIVE" ] || die "expected $MAC_ARCHIVE, not produced"

# --- Push + tag --------------------------------------------------------------
git push "$REMOTE" "$BRANCH"
echo "==> tagging $TAG"
git tag -a "$TAG" "$RELEASE_COMMIT" -m "$TAG"
git push "$REMOTE" "$TAG"

# --- Wait for the Linux archives ---------------------------------------------
echo "==> waiting for the release workflow"
run_id=
tries=0
while [ -z "$run_id" ] && [ "$tries" -lt 30 ]; do
  sleep 5
  tries=$((tries + 1))
  run_id=$(gh run list --workflow release.yml --branch "$TAG" --limit 1 \
    --json databaseId --jq '.[0].databaseId // empty' 2>/dev/null || true)
done
[ -n "$run_id" ] || die "the release workflow did not start for $TAG — the tag is pushed; check the Actions tab"
gh run watch "$run_id" --exit-status || die "the release workflow failed — $TAG is tagged but unpublished"

# --- Assemble + publish ------------------------------------------------------
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
gh release download "$TAG" --pattern 'emailulator_*_linux_*.tar.gz' --dir "$WORK"
cp "$MAC_ARCHIVE" "$WORK/"
count=$(find "$WORK" -name 'emailulator_*.tar.gz' | wc -l | tr -d ' ')
[ "$count" -eq 3 ] || die "expected 3 archives for $TAG, found $count — the draft release is left as it is"

# One checksums.txt over everything, written last: it is what install.sh trusts.
(cd "$WORK" && shasum -a 256 emailulator_*.tar.gz > checksums.txt)
gh release upload "$TAG" "$WORK/$(basename "$MAC_ARCHIVE")" "$WORK/checksums.txt" --clobber
if [ -n "$NOTES" ]; then
  gh release edit "$TAG" --notes-file "$NOTES"
fi
gh release edit "$TAG" --draft=false --latest

echo
echo "Released $TAG"
echo "  commit  $RELEASE_COMMIT"
gh release view "$TAG" --json url,assets \
  -q '"  url     " + .url, "  assets  " + ([.assets[].name] | join(", "))'
echo
echo "Now install what was published, and check it:"
echo "  ./install.sh && emailulator --version"
echo "Then clear the build output: rm -rf dist target/release"
